import numpy as np

np.set_printoptions(precision=6, suppress=True)

X1 = np.array([
    [1.9,  108.0, 22.5],
    [2.07, 89.4,  22.79],
    [2.08, 99.2,  23.1],
    [1.95, 112.8, 22.47]
])

X2 = np.array([
    [2.92, 95.5,  18.95],
    [2.6,  107.8, 20.95],
    [2.86, 100.5, 18.7]
])

mean1 = np.mean(X1, axis=0)
mean2 = np.mean(X2, axis=0)

def calc_S_matrix(X, mean):
    diff = X - mean
    return np.dot(diff.T, diff)

S1 = calc_S_matrix(X1, mean1)
S2 = calc_S_matrix(X2, mean2)

n1, n2 = len(X1), len(X2)
S_star = (S1 + S2) / (n1 + n2 - 2)

S_inv = np.array([
    [340.774244,  -3.193749, 27.363329],
    [  -3.193749,  0.04312,   -0.227296],
    [ 27.363329,  -0.227296,  3.776002]
])
A = np.dot(S_inv, (mean1 - mean2))

# --- ВЫВОД РЕЗУЛЬТАТОВ ---
print("Вектор средних I группы:", mean1)
print("Вектор средних II группы:", mean2)
print("\nМатрица S1 (отклонения I группы):\n", S1)
print("\nМатрица S2 (отклонения II группы):\n", S2)
print("\nСовместная ковариационная матрица S*:\n", S_star)
print("\nОбратная матрица (S*)^-1:\n", S_inv)
print("\nВектор коэффициентов A (a1, a2, a3):\n", A)

# 7. Расчет разности средних векторов (формула 19: X1 - X2)
delta_mean = mean1 - mean2
print("\nРазность средних (X1 - X2):", delta_mean)

# 8. Нахождение вектора коэффициентов A (формула 24: A = S_inv * delta_mean)
A = np.dot(S_inv, delta_mean)
a1, a2, a3 = A

print("\nВектор коэффициентов A:")
print(f"a1 = {a1:.4f}")
print(f"a2 = {a2:.4f}")
print(f"a3 = {a3:.4f}")

# 9. Расчет значений дискриминантной функции для центров групп (формула 25)
f_mean1 = np.dot(A, mean1)
f_mean2 = np.dot(A, mean2)

# 10. Расчет константы дискриминации C (стр. 13 лекции)
C = 0.5 * (f_mean1 + f_mean2)

print(f"\nЗначение f для центра I группы: {f_mean1:.4f}")
print(f"Значение f для центра II группы: {f_mean2:.4f}")
print(f"Пороговая константа C: {C:.4f}")
print("-" * 60)

# 11. КЛАССИФИКАЦИЯ ОБЪЕКТОВ
# Объединяем 4 предприятия из условия и 7 ваших дополнительных
test_objects = np.array([
    # 4 из условия (Вариант 14)
    [2.47, 107.5, 19.30], 
    [2.39, 98.0, 18.85],
    [2.10, 90.8, 17.50],
    [2.64, 102.0, 18.95],
    # 7 ваших дополнительных
    [1.9, 108.0, 22.5], 
    [2.07, 89.4, 22.79], 
    [2.08, 99.2, 23.1], 
    [1.95, 112.8, 22.47], 
    [2.92, 95.5, 18.95], 
    [2.6, 107.8, 20.95], 
    [2.86, 100.5, 18.7]
])

print(f"{'№':<3} | {'f(x)':<10} | {'Результат':<15} | {'Сравнение'}")
print("-" * 60)

for idx, obj in enumerate(test_objects):
    f_x = np.dot(A, obj)
    # Правило из лекции: если f(x) > C, то группа I (так как f_mean1 > f_mean2)
    # Если коэффициенты инвертированы, логика сохраняется относительно близости к f_mean
    if f_mean1 > f_mean2:
        res = "I группа" if f_x > C else "II группа"
    else:
        res = "I группа" if f_x < C else "II группа"
        
    print(f"{idx+1:<3} | {f_x:<10.4f} | {res:<15} | {'f > C' if f_x > C else 'f < C'}")