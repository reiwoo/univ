import pandas as pd
import streamlit as st

st.title(":rainbow[Расчёт НДС гиперупругого материала методом конечных элементов]")
st.divider()

st.subheader("Введение")
st.markdown(
    """
Резины, эластомеры и биологические ткани при нагрузке деформируются **сильно и обратимо**,
поэтому линейная теория упругости для них не подходит.
Аналитически такие задачи решаются редко, а значит нужен **численный алгоритм**.
"""
)
st.subheader("Цель")
st.markdown(
    ":blue-background[Разработать и реализовать на Python (FEniCS) алгоритм расчёта "
    "напряжённо-деформированного состояния гиперупругого тела"
    "на основе МКЭ и метода Ньютона.]"
)

st.subheader("Инструменты")
st.markdown(
    """
    - :green[Python + FEniCS] — _конечно-элементный расчёт_  
    - :orange[Gmsh] — _генерация сеток_
    - :violet[ParaView] — _визуализация полей перемещений и напряжений_
    """
)

st.header("Три модели материала", divider="green")
st.caption("Сравниваются упругие потенциалы Ψ — от них зависит, как материал «отвечает» на нагрузку.")

st.subheader("1. Нео–Гук")
st.latex(
    r"""
    \Psi_{NH} = \frac{\mu}{2}\left(I_C - 3\right) - \mu \ln J + \frac{\lambda}{2}\left(\ln J\right)^2
    """
)
st.text("Простая модель, описывает резиноподобные материалы.")

st.subheader("2. Муни-Ривлин")
st.latex(
    r"""
    \Psi_{MR} = C_{10}\left(I_C - 3\right) + C_{01}\left(II_C - 3\right)
    - \left(2C_{10} + 4C_{01}\right)\ln J + \frac{\lambda}{2}\left(\ln J\right)^2
    """
)
st.text("Две константы вместо одной, учитывает и второй инвариант деформации.")

st.subheader("3. Сен-Венан-Кирхгоф")
st.latex(
    r"""
    \Psi_{SVK} = \frac{\lambda}{2}\left(\mathrm{tr}\,E\right)^2 + \mu\,\mathrm{tr}\left(E^2\right)
    """
)
st.text("Прямое обобщение закона Гука.")
st.subheader("Параметры материала из работы")
with st.echo():
    E = 20.0
    nu = 0.3
    mu = E / (2 * (1 + nu))
    lmbda = E * nu / ((1 + nu) * (1 - 2 * nu))
    st.write(f"μ ≈ {mu:.2f} МПа, λ ≈ {lmbda:.2f} МПа")
st.header("Результаты", divider="red")
st.subheader("Задачи")
st.markdown(
    """
1. **Куб**: закручивание грани. Макс. напряжение по Мизесу выросло с 1.41 до 12.93 (в 9.2 раза) — сильная нелинейность.
2. **Сечение пробкового тоннеля**: плоская деформация под нагрузкой и собственным весом.
3. **Силиконовый каучук**: одноосное растяжение, вязко-гиперупругая модель Гуо, сравнение с экспериментом.
"""
)

st.header("Пример кода", divider="orange")
