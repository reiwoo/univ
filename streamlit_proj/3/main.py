ALL_GENRES = sorted({m["genre"] for m in MOVIES})
ALL_MOODS = ["Весёлое", "Спокойное", "Захватывающее", "Вдохновляющее"]

# ---------------------------------------------------------------------
# Заголовок и имя
# ---------------------------------------------------------------------
st.title("🎬 Подбор фильмов")
st.markdown("Выберите, что вам нравится, а приложение предложит фильмы и даст их **оценить**.")

name = st.text_input("Как вас зовут?")
if name:
    st.write(f"Привет, {name}! Давайте подберём вам фильм.")

# ---------------------------------------------------------------------
# Предпочтения пользователя
# ---------------------------------------------------------------------
st.markdown("### Ваши предпочтения")

genres = st.multiselect("Любимые жанры (если ничего не выбрано, покажем все)", ALL_GENRES)
mood = st.pills("Какое настроение?", ALL_MOODS)
year_from = st.slider("Фильмы не старше (год выпуска от)", 1980, 2020, 1990)

left, right = st.columns(2)
sort_by = left.radio("Сортировать по", ["Рейтингу", "Году выпуска"])
only_top = right.checkbox("Только с рейтингом 8.5 и выше")
show_about = right.toggle("Показывать описания", value=True)

# ---------------------------------------------------------------------
# Подбор
# ---------------------------------------------------------------------
found = [
    m for m in MOVIES
    if (not genres or m["genre"] in genres)
    and (mood is None or m["mood"] == mood)
    and m["year"] >= year_from
    and (not only_top or m["rating"] >= 8.5)
]
found.sort(key=lambda m: m["rating"] if sort_by == "Рейтингу" else m["year"], reverse=True)

st.markdown(f"### Подходящие фильмы: {len(found)}")

if not found:
    st.write("Ничего не нашлось. Попробуйте ослабить фильтры.")

if st.button("🎲 Мне повезёт", type="primary", disabled=not found):
    st.write("Попробуйте посмотреть:", random.choice(found)["title"])

# ---------------------------------------------------------------------
# Список фильмов с оценкой
# ---------------------------------------------------------------------
report_lines = []

for m in found:
    st.markdown(f"**{m['title']}** ({m['year']}) · {m['genre']} · ⭐ {m['rating']}")
    if show_about:
        st.write(m["about"])

    col_stars, col_link = st.columns([3, 2])
    with col_stars:
        stars = st.feedback("stars", key=f"stars_{m['title']}")
    with col_link:
        st.link_button("Найти в Кинопоиске", f"https://www.kinopoisk.ru/index.php?kp_query={quote(m['title'])}")

    if stars is not None:
        report_lines.append(f"{m['title']}: {stars + 1} из 5")

# ---------------------------------------------------------------------
# Мои оценки + скачивание
# ---------------------------------------------------------------------
if report_lines:
    st.markdown("### Ваши оценки")
    for line in report_lines:
        st.write(line)

    st.download_button(
        "Скачать мои оценки",
        "\n".join(report_lines),
        file_name="my_movie_ratings.txt",
    )

# ---------------------------------------------------------------------
# Отзыв (форма)
# ---------------------------------------------------------------------
st.markdown("### Отзыв о приложении")
with st.form("review_form"):
    review = st.text_area("Что понравилось, чего не хватает?")
    submitted = st.form_submit_button("Отправить отзыв")

if submitted:
    st.write("Спасибо за отзыв!")
    st.write(f"Ваш отзыв: {review}")